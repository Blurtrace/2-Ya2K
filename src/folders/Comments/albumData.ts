export type MediaItem = {
  id: string;
  year: number | null;
  displayDate: string;
  displayDateEn?: string;
  location?: string;
  locationEn?: string;
  sender: 'Zharick' | 'Roselis' | 'Dainys' | 'Familia' | 'Jandy';
  quote: string;
  quoteEn?: string;
  src: string;
  mediaType: 'image' | 'video' | 'card';
  notes?: string;
};

export const getAlbumQuote = (item: MediaItem, lang: string): string => {
  if (lang === 'en' && item.quoteEn) {
    return item.quoteEn;
  }
  return item.quote;
};

export const getAlbumLocation = (item: MediaItem, lang: string): string | undefined => {
  if (lang === 'en' && item.locationEn) {
    return item.locationEn;
  }
  return item.location;
};

export const getAlbumDisplayDate = (item: MediaItem, lang: string): string => {
  if (lang === 'en' && item.displayDateEn) {
    return item.displayDateEn;
  }
  return item.displayDate;
};

